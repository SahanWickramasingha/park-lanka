create table cashier_shifts (
 id bigint generated by default as identity primary key,
 owner_key varchar(160) not null, cashier varchar(128) not null, branch_id bigint not null references branches(id), branch varchar(100) not null,
 active_key varchar(200) unique, open_request_key varchar(36) not null unique, open_fingerprint varchar(64) not null,
 close_request_key varchar(36) unique, close_fingerprint varchar(64), opened_at timestamp(6) with time zone not null, closed_at timestamp(6) with time zone,
 opening_cash numeric(12,2) not null, counted_cash numeric(12,2), expected_cash numeric(12,2), difference numeric(12,2),
 cash_collections numeric(12,2), card_collections numeric(12,2), cash_refunds numeric(12,2), cash_voids numeric(12,2), reason varchar(500)
);
create index shift_owner_time on cashier_shifts(owner_key,branch_id,opened_at);
alter table payments add column shift_id bigint references cashier_shifts(id);
