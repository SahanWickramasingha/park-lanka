create table audit_records (
 id bigint generated by default as identity primary key, actor varchar(128) not null, action varchar(100) not null,
 target varchar(160) not null, branch_id bigint, occurred_at timestamp(6) with time zone not null, reason varchar(500),
 before_details varchar(12000), after_details varchar(12000)
);
create index audit_time_branch on audit_records(occurred_at,branch_id,id);
