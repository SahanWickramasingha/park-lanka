create table payment_corrections (
 id bigint generated by default as identity primary key, payment_id bigint not null references payments(id),
 type varchar(8) not null, amount numeric(12,2) not null, reason varchar(500) not null, actor varchar(128) not null,
 occurred_at timestamp(6) with time zone not null, branch_id bigint not null, branch varchar(100) not null, method varchar(16) not null,
 external_reference varchar(80), movement_shift_id bigint references cashier_shifts(id),
 request_key varchar(36) not null unique, fingerprint varchar(64) not null,
 constraint uq_external_correction unique(payment_id,external_reference)
);
create index correction_period_branch on payment_corrections(occurred_at,branch_id,id);
