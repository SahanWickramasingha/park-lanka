create table backup_jobs (
 id bigint generated by default as identity primary key, job_key varchar(36) not null unique, kind varchar(24) not null,
 status varchar(24) not null, actor varchar(128) not null, engine varchar(16), created_at timestamp(6) with time zone not null,
 completed_at timestamp(6) with time zone, size_bytes bigint, file_name varchar(100), failure varchar(500), source_job_id bigint,
 restore_plan varchar(100)
);
